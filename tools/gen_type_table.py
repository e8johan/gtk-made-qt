#!/usr/bin/env python3
"""Write the table of the library's GType functions, for GtkBuilder.

GtkBuilder turns class names in .ui files into types by calling
<name>_get_type. The library is static with hidden symbols, so it cannot
find its own functions with g_module_symbol; it uses this table instead.
usage: gen_type_table.py <output.inc> <source.cpp>...
"""
import re, sys
out, sources = sys.argv[1], sys.argv[2:]
names = set()
for p in sources:
    s = open(p).read()
    for m in re.finditer(r"G_DEFINE_[A-Z_]*TYPE[A-Z_]*\s*\(\s*\w+\s*,\s*(\w+)\s*,", s):
        names.add(m.group(1) + "_get_type")
    for m in re.finditer(r"^GType\s+(\w+_get_type)\s*\(\s*void\s*\)", s, re.M):
        names.add(m.group(1))
with open(out, "w") as f:
    f.write("/* Generated by tools/gen_type_table.py. Do not edit. */\n")
    for n in sorted(names):
        f.write("TYPE_FN (%s)\n" % n)
