#!/usr/bin/env python3
"""Write the table of keysym names (gdk_keyval_name, gdk_keyval_from_name).

GDK keyvals are X keysyms; the names come from X11/keysymdef.h (MIT).
usage: gen_keysym_table.py <output.inc> <keysymdef.h>
"""
import re, sys
out, src = sys.argv[1], sys.argv[2]
entries = []
for line in open(src, encoding="latin-1"):
    m = re.match(r"#define XK_(\w+)\s+(0x[0-9a-fA-F]+)", line)
    if m:
        entries.append((m.group(1), int(m.group(2), 16), "deprecated" in line))
with open(out, "w") as f:
    f.write("/* Generated by tools/gen_keysym_table.py from X11/keysymdef.h. Do not edit. */\n")
    # by name, for lookups; a deprecated alias never wins the value's name
    for name, val, dep in entries:
        f.write('{ "%s", 0x%x, %d },\n' % (name, val, 1 if dep else 0))
