#!/usr/bin/env python3
"""Write include/gdk/gdkkeysyms.h from X11/keysymdef.h (MIT).

GDK keyvals are X keysyms: GDK_KEY_<name> for every XK_<name>, and the
GTK 1/2 spelling GDK_<name> where GTK 2 had it.
usage: gen_gdk_keysyms.py <keysymdef.h> <gdkkeysyms.h>
"""
import re, sys
src, out = sys.argv[1], sys.argv[2]
entries, seen = [], set()
for line in open(src, encoding="latin-1"):
    m = re.match(r"#define XK_(\w+)\s+(0x[0-9a-fA-F]+)", line)
    if m and m.group(1) not in seen:
        seen.add(m.group(1))
        entries.append((m.group(1), m.group(2).lower()))
with open(out, "w") as f:
    f.write("/* Generated by tools/gen_gdk_keysyms.py from X11/keysymdef.h: GDK key symbol\n"
            " * values (the X11 standard ones). Do not edit. */\n")
    f.write("#ifndef GTKQT_GDK_KEYSYMS_H\n#define GTKQT_GDK_KEYSYMS_H\n\n")
    for name, val in entries:
        f.write("#define GDK_KEY_%s %s\n" % (name, val))
    f.write("\n/* GTK 1/2 spelling (GDK_Return etc.) */\n")
    f.write("#if !defined(GTKQT_API_VERSION) || GTKQT_API_VERSION <= 2 || defined(GDK_KEYSYMS_COMPAT)\n")
    for name, _ in entries:
        f.write("#define GDK_%s GDK_KEY_%s\n" % (name, name))
    f.write("#endif\n\n#endif\n")
